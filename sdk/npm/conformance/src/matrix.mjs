/**
 * Renders COMPLIANCE.md from results. Nothing in the file is written by hand, and
 * nothing in it varies between runs: no time, no commit, no version, so the
 * committed copy is stale only when a result or a check changed.
 *
 * It renders only results that passed and only results for the whole current
 * suite. A runtime with a shim and no results is an error, never a blank column.
 */
import { allChecks } from './scenarios.mjs';
import { RESULTS_SCHEMA } from './run.mjs';

export const REGENERATE = 'node sdk/npm/conformance/bin/prism-conformance.mjs matrix --write';

/** The cell of one check. */
function checkCell(status) {
  if (status === undefined || status === 'n/a') return 'N/A';
  return status === 'pass' ? '+' : '-';
}

/** The cell of one feature: `+` only when every check in it passed. */
function featureCell(statuses) {
  if (statuses.length === 0 || statuses.every((status) => status === 'n/a')) return 'N/A';
  return statuses.every((status) => status === 'pass' || status === 'n/a') ? '+' : '-';
}

/** Why these results cannot be published. */
export function problemsOfResults(results, runtime, features) {
  if (results?.schema !== RESULTS_SCHEMA) return [`${runtime}: the results are not ${RESULTS_SCHEMA}`];
  const problems = [];
  if (results.runtime !== runtime) problems.push(`${runtime}: the results are for ${results.runtime}`);
  if (!results.complete) problems.push(`${runtime}: the results are from a partial run`);
  if (!results.passed) {
    const failed = results.checks.filter((check) => check.status === 'fail' || check.status === 'unexpected-pass').map((check) => `${check.id} (${check.status})`);
    problems.push(`${runtime}: the run did not pass: ${failed.join(', ')}`);
  }
  const reported = new Set(results.checks.map((check) => check.id));
  const expected = new Set(allChecks(features).map((check) => check.id));
  const missing = [...expected].filter((id) => !reported.has(id));
  const unknown = [...reported].filter((id) => !expected.has(id));
  if (missing.length) problems.push(`${runtime}: no result for ${missing.join(', ')}`);
  if (unknown.length) problems.push(`${runtime}: results for checks this suite does not have: ${unknown.join(', ')}`);
  return problems;
}

const row = (cells) => `| ${cells.join(' | ')} |`;
const escapeCell = (text) => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

/**
 * @param {{ features: object[], runtimes: { name: string, title: string, results: object | null }[] }} input
 * A runtime's `results` is null when it has no shim, and every cell of it is then N/A.
 */
export function renderMatrix({ features, runtimes }) {
  const problems = runtimes.filter((runtime) => runtime.results).flatMap((runtime) => problemsOfResults(runtime.results, runtime.name, features));
  if (problems.length) throw new Error(`cannot publish these results:\n${problems.join('\n')}`);
  const statusOf = runtimes.map((runtime) => new Map((runtime.results?.checks ?? []).map((check) => [check.id, check])));
  const titles = runtimes.map((runtime) => runtime.title);
  const lines = [
    `<!-- @generated by \`${REGENERATE}\`. Do not edit: CI regenerates this file and fails when the committed copy differs. -->`,
    '',
    '# COMPLIANCE',
    '',
    'Which Prism runtime passes which part of the runtime contract, from the results of [`@prism-code/conformance`](sdk/npm/conformance/README.md).',
    '[CONFORMANCE.md](CONFORMANCE.md) is a different register: the SDK capabilities the Rust tests cover.',
    '',
    '| Cell | Meaning |',
    '| --- | --- |',
    '| `+` | Every check passed. |',
    '| `-` | At least one check failed and the runtime declared that failure, or the check is a placeholder for work that is not on main. |',
    '| `N/A` | Nothing was measured: the runtime has no shim yet, or it declares the feature does not apply to it. |',
    '',
    '## Features',
    '',
    row(['Feature', 'Checks', ...titles]),
    row(['---', '---', ...titles.map(() => '---')]),
  ];
  for (const feature of features) {
    const cells = statusOf.map((statuses) => featureCell(feature.checks.map((check) => statuses.get(check.id)?.status).filter(Boolean)));
    lines.push(row([`${feature.title} (\`${feature.feature}\`)`, String(feature.checks.length), ...cells]));
  }
  lines.push('', '## Checks', '');
  for (const feature of features) {
    lines.push(`### ${feature.title}`, '', row(['Check', 'Asks', ...titles]), row(['---', '---', ...titles.map(() => '---')]));
    for (const check of feature.checks) {
      lines.push(row([`\`${check.id}\``, escapeCell(check.title), ...statusOf.map((statuses) => checkCell(statuses.get(check.id)?.status))]));
    }
    lines.push('');
  }
  const declared = [];
  runtimes.forEach((runtime, i) => {
    for (const check of allChecks(features)) {
      const result = statusOf[i].get(check.id);
      if (result?.status === 'xfail') declared.push(row([runtime.title, `\`${check.id}\``, escapeCell(result.reason)]));
    }
  });
  lines.push('## Expected failures', '');
  if (declared.length) lines.push(row(['Runtime', 'Check', 'Why']), row(['---', '---', '---']), ...declared, '');
  else lines.push('None.', '');
  return lines.join('\n');
}

/** Line endings aside, is the committed text current? A Windows checkout may hold CRLF. */
export const sameMatrix = (committed, rendered) => committed.replace(/\r\n/g, '\n') === rendered;
