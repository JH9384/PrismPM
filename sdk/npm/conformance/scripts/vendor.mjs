/**
 * Copies the pure modules the harness needs from its siblings into src/vendor/,
 * byte for byte below a header that names the origin. The reasons are the ones
 * in sdk/npm/verify/scripts/vendor.mjs: `@prism-code/spec` is not published, the
 * repository has no npm workspace, and a harness must not import the runtime it
 * judges. `prism-code` is the origin of the BLAKE3 file only because Node has no
 * BLAKE3; expected digests in the scenarios are pinned values from ADR-015, so a
 * wrong hash here cannot make a wrong runtime pass.
 *
 * `node scripts/vendor.mjs` writes the files. `--check` fails when any of them
 * differs from what its origin would produce today.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const read = (relative) => readFileSync(here(relative), 'utf8').replace(/\r\n/g, '\n');
const check = process.argv.includes('--check');

const header = (origin) => `// GENERATED by scripts/vendor.mjs from ${origin}. Do not edit; run \`node scripts/vendor.mjs\`.\n\n`;
const VERDICT = 'schemas/verdict/verdict-v1.schema.json';

const outputs = {
  'src/vendor/blake3.mjs': header('sdk/npm/prism-code/src/blake3.mjs') + read('../../prism-code/src/blake3.mjs'),
  'src/vendor/json-schema.mjs': header('sdk/npm/spec/test/json-schema.mjs') + read('../../spec/test/json-schema.mjs'),
  'src/vendor/verdict-schema.mjs':
    header(`sdk/npm/spec/${VERDICT}`) + `export const VERDICT_SCHEMA = Object.freeze(${JSON.stringify(JSON.parse(read(`../../spec/${VERDICT}`)))});\n`,
};

let stale = 0;
for (const [path, content] of Object.entries(outputs)) {
  if (check) {
    let current = null;
    try {
      current = read(`../${path}`);
    } catch {}
    if (current !== content) {
      console.error(`${path} is stale; run node scripts/vendor.mjs`);
      stale++;
    }
  } else {
    writeFileSync(here(`../${path}`), content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
if (check) console.log('vendored files are current');
