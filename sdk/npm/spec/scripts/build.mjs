#!/usr/bin/env node
/**
 * Writes the files this package generates from its own directories. None of
 * them is committed (see .gitignore); `npm run build` makes them, `prepare`,
 * `prepack` and `pretest` run it, and the tests and the docs generator call
 * `build()` themselves, so a fresh checkout works with one command.
 *
 *   index.mjs                the entry point: constants.mjs plus SCHEMAS,
 *                            HOLO_SCHEMAS and one PREDICATE_TYPE constant per predicate
 *   index.d.ts               its types: constants.d.ts, every file in types/ and
 *                            predicates/, the document unions, the registries
 *   types/documents.d.ts     types from schemas/holo and schemas/documents
 *   types/predicate-map.d.ts PredicateMap and PredicateType from predicates/
 *   predicates/registry.json the predicate registry, from the predicate rows
 *
 * Adding a schema, a document version or a predicate means adding files. No
 * list in this package names them; this script finds them.
 *
 *   node scripts/build.mjs   (reports on stderr, so `npm pack --json` stays parseable)
 */
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { PACKAGE_DIR, discover, pascal, registryOf } from './discover.mjs';
import { OUTPUT as DOCUMENT_TYPES, generate as generateDocumentTypes } from './generate-types.mjs';

export { PACKAGE_DIR, discover };

const BANNER = 'GENERATED by scripts/build.mjs from the files in this package. Not committed; run `npm run build`.';
const quote = (text) => `'${text}'`;

function generatedMjs(found) {
  const lines = [`// ${BANNER}`, '', "export * from './constants.mjs';", '', 'const freeze = Object.freeze;', ''];
  lines.push('/** The `schema` member of each document this package has a JSON Schema for, mapped to the schema file. */');
  lines.push('export const SCHEMAS = freeze({', ...found.documents.map((d) => `  ${quote(d.name)}: ${quote(d.path)},`), '});', '');
  lines.push('/** JSON Schemas for the decoded holo sections. */');
  lines.push('export const HOLO_SCHEMAS = freeze({', ...found.holo.map((h) => `  ${h.key}: ${quote(h.path)},`), '});', '');
  for (const p of found.predicates) {
    lines.push(`/** ${p.status}. Type: \`${p.types}\`. Schema: ${p.schema ? `\`${p.schema}\`` : 'none yet'}. */`);
    lines.push(`export const ${p.constant} = ${quote(p.predicateType)};`);
  }
  return `${lines.join('\n')}\n`;
}

function generatedDts(found, typeFiles) {
  const lines = [`// ${BANNER}`, '/**', ' * @prism-code/spec: the Prism formats as types, JSON Schemas and WIT.', ' * Constants only; no functions.', ' */'];
  if (found.documents.length > 0) {
    lines.push(`import type {`, ...found.documents.map((d) => `  ${d.type},`), `} from './types/documents.js';`);
  }
  lines.push('', "export * from './constants.js';");
  for (const name of typeFiles) lines.push(`export type * from './types/${name}.js';`);
  for (const p of found.predicates) {
    lines.push(`export { ${p.constant} } from './predicates/${p.stem}.js';`, `export type * from './predicates/${p.stem}.js';`);
  }
  lines.push('');
  for (const family of found.families) {
    lines.push(`/** Any ${family.family} document, discriminated by \`schema\`. */`);
    lines.push(`export type ${family.type} = ${family.members.join(' | ')};`);
  }
  lines.push('', '/** The `schema` member of every document this package has a JSON Schema for. */');
  lines.push(found.documents.length ? ['export type DocumentSchemaName =', ...found.documents.map((d, i) => `  | ${quote(d.name)}${i === found.documents.length - 1 ? ';' : ''}`)].join('\n') : 'export type DocumentSchemaName = never;', '');
  lines.push('/** Document `schema` value to package-relative JSON Schema path. */');
  lines.push('export declare const SCHEMAS: Readonly<Record<DocumentSchemaName, string>>;', '');
  lines.push('export declare const HOLO_SCHEMAS: Readonly<{', ...found.holo.map((h) => `  ${h.key}: ${quote(h.path)};`), '}>;', '');
  return `${lines.join('\n')}\n`;
}

function generatedPredicateMap(found) {
  const body = (p) => `${pascal(p.name)}PredicateV${p.version}`;
  const lines = [`// ${BANNER}`, '/** Predicate type URI to predicate body, from the files in predicates/. */'];
  for (const p of found.predicates) lines.push(`import type { ${body(p)} } from '../predicates/${p.stem}.js';`);
  lines.push('', 'export interface PredicateMap {', ...found.predicates.map((p) => `  ${quote(p.predicateType)}: ${body(p)};`), '}', '');
  lines.push('export type PredicateType = keyof PredicateMap;');
  return `${lines.join('\n')}\n`;
}

/**
 * Every generated file as relative path to text. Pure: it reads the package
 * directory and writes nothing.
 */
export function render(dir = PACKAGE_DIR) {
  const found = discover(dir);
  const typeFiles = [...new Set([...found.types, 'documents', 'predicate-map'])].sort();
  return new Map([
    [DOCUMENT_TYPES, generateDocumentTypes(pathToFileURL(`${dir.replace(/[\\/]+$/, '')}/`))],
    ['types/predicate-map.d.ts', generatedPredicateMap(found)],
    ['predicates/registry.json', `${JSON.stringify(registryOf(found), null, 2)}\n`],
    ['index.mjs', generatedMjs(found)],
    ['index.d.ts', generatedDts(found, typeFiles)],
  ]);
}

const sleep = (ms) => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);

/** Write through a temporary file so a test that starts in parallel never reads half a file. */
function writeAtomic(path, text) {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return false;
  mkdirSync(dirname(path), { recursive: true });
  const temp = `${path}.${process.pid}.tmp`;
  writeFileSync(temp, text);
  for (let attempt = 0; ; attempt++) {
    try {
      renameSync(temp, path);
      return true;
    } catch (error) {
      // Windows refuses to replace a file another process has open for a moment.
      if (attempt >= 40 || !['EPERM', 'EBUSY', 'EACCES'].includes(error.code)) {
        rmSync(temp, { force: true });
        if (existsSync(path) && readFileSync(path, 'utf8') === text) return false;
        throw error;
      }
      sleep(25);
    }
  }
}

/**
 * Write the generated files that are missing or differ.
 * @returns {string[]} the relative paths written
 */
export function build(dir = PACKAGE_DIR) {
  const written = [];
  for (const [rel, text] of render(dir)) if (writeAtomic(join(dir, rel), text)) written.push(rel);
  return written;
}

/** Build, then import the generated entry point. */
export async function loadSpec(dir = PACKAGE_DIR) {
  build(dir);
  return import(pathToFileURL(join(dir, 'index.mjs')).href);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const written = build();
  console.error(written.length ? `wrote ${written.join(', ')}` : 'generated files are current');
}
