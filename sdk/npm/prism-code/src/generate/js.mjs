/**
 * The JavaScript writer of `prism-code generate` (issue #289): turns the code
 * model into ES modules with TypeScript declarations beside them. The output
 * imports nothing, runs in Node and browsers, and is written to read as if a
 * person wrote it: named constants, one class per application, doc comments
 * taken from the WIT world and the model.
 *
 * `write(model)` returns `[path, text]` pairs, LF line ends, in a fixed order.
 */
import { fail } from '../errors.mjs';

const HEADER = (from) => `// Generated by \`prism-code generate\` from ${from}.\n// Do not edit: run \`prism-code generate\` again.\n`;

const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const lines = (...parts) => `${parts.flat().filter((p) => p !== null).join('\n')}\n`;
const doc = (indent, text) => (text.length === 0 ? null : text.length === 1 ? `${indent}/** ${text[0]} */` : [`${indent}/**`, ...text.map((t) => `${indent} * ${t}`.trimEnd()), `${indent} */`].join('\n'));

/** How each scalar WIT type crosses into JavaScript: its TypeScript type, and how a core result is lifted. */
const LIFT = Object.freeze({
  bool: { ts: 'boolean', lift: (x) => `${x} !== 0` },
  u8: { ts: 'number', lift: (x) => `${x} >>> 0` },
  u16: { ts: 'number', lift: (x) => `${x} >>> 0` },
  u32: { ts: 'number', lift: (x) => `${x} >>> 0` },
  s8: { ts: 'number', lift: (x) => `${x} | 0` },
  s16: { ts: 'number', lift: (x) => `${x} | 0` },
  s32: { ts: 'number', lift: (x) => `${x} | 0` },
  char: { ts: 'number', lift: (x) => `${x} >>> 0` },
  u64: { ts: 'bigint', lift: (x) => `BigInt.asUintN(64, ${x})` },
  s64: { ts: 'bigint', lift: (x) => `BigInt.asIntN(64, ${x})` },
  f32: { ts: 'number', lift: (x) => x },
  f64: { ts: 'number', lift: (x) => x },
});
const lower = (p) => (p.type === 'bool' ? `${p.name} ? 1 : 0` : p.name);

const camel = (name) => name.replace(/[-_]+([a-z0-9])/g, (_, c) => c.toUpperCase());

/**
 * The host side of each world, beyond what WIT can say: how a request reaches
 * the guest and how its response comes back. The core-wasm world states it in
 * its file's header comment.
 */
const PROTOCOLS = Object.freeze({
  'hologram:guest/core-wasm@1': {
    js: [
      '/**',
      ' * Send one request to a fresh instance of the guest and return a copy of its response.',
      ' * The guest allocator never frees, so every request gets its own instance.',
      ' * @param {WebAssembly.Module} module',
      ' * @param {Uint8Array} request',
      ' * @returns {Uint8Array}',
      ' */',
      'export function dispatch(module, request) {',
      '  const guest = instantiate(module);',
      '  const offset = guest.holoAlloc(request.length);',
      '  new Uint8Array(guest.memory.buffer, offset, request.length).set(request);',
      '  const packed = guest.holoRun(offset, request.length);',
      '  const at = Number(packed >> 32n);',
      '  const length = Number(packed & 0xffffffffn);',
      '  if (at + length > guest.memory.buffer.byteLength) {',
      '    throw new RangeError(`the guest answered ${length} bytes at ${at}, outside its memory`);',
      '  }',
      '  return new Uint8Array(guest.memory.buffer.slice(at, at + length));',
      '}',
    ],
    ts: [
      '/**',
      ' * Send one request to a fresh instance of the guest and return a copy of its response.',
      ' * The guest allocator never frees, so every request gets its own instance.',
      ' */',
      'export declare function dispatch(module: WebAssembly.Module, request: Uint8Array): Uint8Array;',
    ],
  },
});

function worldFiles(world) {
  const protocol = PROTOCOLS[world.contract] ?? fail('generate.world', `the js writer has no host protocol for ${world.contract}`);
  if (world.imports.length !== 0) fail('generate.world', `the js writer binds import-free worlds; ${world.contract} has imports`);
  const from = `the WIT world ${world.contract} (${world.file})`;
  const kinds = [...world.exports.map((f) => [f.name, 'function']), [world.memory, 'memory']].sort(([a], [b]) => (a < b ? -1 : 1));
  const bound = world.exports.map((f) => {
    const lift = LIFT[f.result?.type]?.lift ?? ((x) => x);
    const call = `exports.${f.name}(${f.params.map(lower).join(', ')})`;
    return [doc('    ', f.docs), `    ${camel(f.name)}: (${f.params.map((p) => p.name).join(', ')}) => ${f.result ? lift(call) : `void ${call}`},`];
  });
  const js = lines(
    HEADER(from),
    '/** The world these bindings were generated from. It equals `inputs.world` in prismpm.lock. */',
    'export const WORLD = Object.freeze({',
    `  contract: ${quote(world.contract)},`,
    `  blake3: ${quote(world.digest.blake3)},`,
    `  sha256: ${quote(world.digest.sha256)},`,
    '});',
    '',
    '/** Every export the world requires, and its kind. */',
    'const EXPORTS = Object.freeze({',
    kinds.map(([name, kind]) => `  ${name}: ${quote(kind)},`),
    '});',
    '',
    '/**',
    ' * Instantiate a compiled guest and check that it offers exactly the world\'s exports.',
    ' * The guest imports nothing.',
    ' * @param {WebAssembly.Module} module',
    ' */',
    'export function instantiate(module) {',
    '  const { exports } = new WebAssembly.Instance(module, {});',
    '  const names = Object.keys(exports).sort();',
    '  const expected = Object.keys(EXPORTS).sort();',
    '  if (names.join() !== expected.join() || names.some((name) => kindOf(exports[name]) !== EXPORTS[name])) {',
    '    throw new TypeError(`the guest exports ${names.join(\', \')}; ${WORLD.contract} requires ${expected.join(\', \')}`);',
    '  }',
    '  return {',
    `    ${world.memory}: exports.${world.memory},`,
    bound.flat(),
    '  };',
    '}',
    '',
    'function kindOf(value) {',
    '  return value instanceof WebAssembly.Memory ? \'memory\' : typeof value === \'function\' ? \'function\' : \'other\';',
    '}',
    '',
    protocol.js,
  );
  const ts = lines(
    HEADER(from),
    '/** The world these bindings were generated from. It equals `inputs.world` in prismpm.lock. */',
    'export declare const WORLD: {',
    `  readonly contract: ${quote(world.contract)};`,
    '  readonly blake3: string;',
    '  readonly sha256: string;',
    '};',
    '',
    `/** A guest of ${world.contract}, instantiated. */`,
    'export interface Guest {',
    `  readonly ${world.memory}: WebAssembly.Memory;`,
    world.exports.map((f) => [
      doc('  ', f.docs),
      `  ${camel(f.name)}(${f.params.map((p) => `${p.name}: ${LIFT[p.type].ts}`).join(', ')}): ${f.result ? LIFT[f.result.type].ts : 'void'};`,
    ]).flat(),
    '}',
    '',
    '/** Instantiate a compiled guest and check that it offers exactly the world\'s exports. */',
    'export declare function instantiate(module: WebAssembly.Module): Guest;',
    '',
    protocol.ts,
  );
  return [
    ['world.js', js],
    ['world.d.ts', ts],
  ];
}

function operationsFiles(application) {
  const api = application.interface;
  const { type, errorType, operationType } = { type: application.type, ...api };
  const codeType = `${errorType}Code`;
  const from = `${application.name}'s model (${application.schema}, blake3:${application.model.blake3})`;
  const fallback = {
    'unsupported-version': `${application.name} does not answer request version ${api.version}.`,
    'unknown-operation': `${application.name} does not know this operation.`,
  };
  const description = [`A client for ${application.name}.`, ...(application.description ? ['', application.description] : []), ''];
  const methods = api.operations.map((o) => [
    '',
    `  /** ${o.label}: \`${api.method}(${quote(o.name)}, left, right)\`. */`,
    `  ${o.method}(left, right) {`,
    `    return this.${api.method}(${quote(o.name)}, left, right);`,
    '  }',
  ]);
  const js = lines(
    HEADER(from),
    '/** The model this client was generated from. It equals `inputs.model` in prismpm.lock. */',
    'export const MODEL = Object.freeze({',
    `  name: ${quote(application.name)},`,
    `  blake3: ${quote(application.model.blake3)},`,
    `  sha256: ${quote(application.model.sha256)},`,
    '});',
    '',
    `/** Every operation ${application.name} accepts, by its request name. */`,
    `export const OPERATIONS = Object.freeze([${api.operations.map((o) => quote(o.name)).join(', ')}]);`,
    '',
    `const VERSION = ${quote(api.version)};`,
    'const MIN = -(2n ** 63n);',
    'const MAX = 2n ** 63n - 1n;',
    'const MESSAGES = Object.freeze({',
    api.errors.map((e) => `  ${/^[a-z]+$/.test(e.code) ? e.code : quote(e.code)}: ${quote(e.message ?? fallback[e.code])},`),
    '});',
    '',
    'const encoder = new TextEncoder();',
    'const decoder = new TextDecoder(\'utf-8\', { fatal: true });',
    '',
    `/** A request ${application.name} refused. \`code\` is the guest's answer, such as \`${api.errors[0].code}\`. */`,
    `export class ${errorType} extends Error {`,
    '  constructor(code) {',
    `    super(MESSAGES[code] ?? \`${application.name} refused the request: \${code}.\`);`,
    `    this.name = ${quote(errorType)};`,
    '    this.code = code;',
    '  }',
    '}',
    '',
    '/**',
    description.map((d) => ` * ${d}`.trimEnd()),
    ' * `dispatch` sends request bytes to the guest and returns its response bytes:',
    ' * `app.dispatch` of an application prism-code\'s `load()` opened, or',
    ' * `(request) => dispatch(module, request)` with `dispatch` from ./world.js.',
    ' */',
    `export class ${type} {`,
    '  #dispatch;',
    '',
    '  /** @param {(request: Uint8Array) => Uint8Array | Promise<Uint8Array>} dispatch */',
    '  constructor(dispatch) {',
    `    if (typeof dispatch !== 'function') throw new TypeError('${type} needs a dispatch function');`,
    '    this.#dispatch = dispatch;',
    '  }',
    methods.flat(),
    '',
    '  /**',
    '   * Apply `operation` to two signed 64-bit integers. Resolves to the result;',
    `   * rejects with ${errorType} when ${application.name} refuses, for example on overflow.`,
    '   */',
    `  async ${api.method}(operation, left, right) {`,
    '    if (!OPERATIONS.includes(operation)) throw new TypeError(`unknown operation ${operation}`);',
    '    const request = encoder.encode(`${VERSION}\\t${operation}\\t${int64(left)}\\t${int64(right)}`);',
    '    const [version, status, value] = decoder.decode(await this.#dispatch(request)).split(\'\\t\');',
    `    if (version !== VERSION) throw new ${errorType}('unsupported-version');`,
    '    if (status === \'ok\') return BigInt(value);',
    `    throw new ${errorType}(value);`,
    '  }',
    '}',
    '',
    'function int64(value) {',
    '  const n = typeof value === \'bigint\' ? value : Number.isSafeInteger(value) ? BigInt(value) : null;',
    '  if (n === null || n < MIN || n > MAX) throw new RangeError(`${value} is not a signed 64-bit integer`);',
    '  return n.toString();',
    '}',
  );
  const ts = lines(
    HEADER(from),
    '/** The model this client was generated from. It equals `inputs.model` in prismpm.lock. */',
    'export declare const MODEL: {',
    `  readonly name: ${quote(application.name)};`,
    '  readonly blake3: string;',
    '  readonly sha256: string;',
    '};',
    '',
    `/** An operation ${application.name} accepts, by its request name. */`,
    `export type ${operationType} = ${api.operations.map((o) => quote(o.name)).join(' | ')};`,
    `export declare const OPERATIONS: readonly ${operationType}[];`,
    '',
    '/** A signed 64-bit integer: a bigint, or a number that is a safe integer. */',
    'export type Int64 = bigint | number;',
    '',
    `/** Every answer with which ${application.name} refuses a request. */`,
    `export type ${codeType} = ${api.errors.map((e) => quote(e.code)).join(' | ')};`,
    '',
    `/** A request ${application.name} refused. \`code\` is the guest's answer. */`,
    `export declare class ${errorType} extends Error {`,
    `  constructor(code: ${codeType});`,
    `  readonly code: ${codeType};`,
    '}',
    '',
    '/** Sends request bytes to the guest and returns its response bytes. */',
    'export type Dispatch = (request: Uint8Array) => Uint8Array | Promise<Uint8Array>;',
    '',
    doc('', description.slice(0, -1)),
    `export declare class ${type} {`,
    '  constructor(dispatch: Dispatch);',
    api.operations.map((o) => [`  /** ${o.label}: \`${api.method}(${quote(o.name)}, left, right)\`. */`, `  ${o.method}(left: Int64, right: Int64): Promise<bigint>;`]).flat(),
    `  /** Apply \`operation\` to two signed 64-bit integers; rejects with ${errorType} when ${application.name} refuses. */`,
    `  ${api.method}(operation: ${operationType}, left: Int64, right: Int64): Promise<bigint>;`,
    '}',
  );
  return [
    [`${application.file}.js`, js],
    [`${application.file}.d.ts`, ts],
  ];
}

function bytesFiles(application) {
  const { type } = application;
  const from = `${application.name}'s model (${application.schema}, blake3:${application.model.blake3})`;
  const description = [`A client for ${application.name}, over request and response bytes.`, ...(application.description ? ['', application.description] : []), ''];
  const model = [
    '/** The model this client was generated from. It equals `inputs.model` in prismpm.lock. */',
    'export const MODEL = Object.freeze({',
    `  name: ${quote(application.name)},`,
    `  blake3: ${quote(application.model.blake3)},`,
    `  sha256: ${quote(application.model.sha256)},`,
    '});',
  ];
  const js = lines(
    HEADER(from),
    model,
    '',
    '/**',
    description.map((d) => ` * ${d}`.trimEnd()),
    ` * ${application.name}'s model describes no typed operations, so the client sends bytes.`,
    ' * `dispatch` is `app.dispatch` of an application prism-code\'s `load()` opened, or',
    ' * `(request) => dispatch(module, request)` with `dispatch` from ./world.js.',
    ' */',
    `export class ${type} {`,
    '  #dispatch;',
    '',
    '  /** @param {(request: Uint8Array) => Uint8Array | Promise<Uint8Array>} dispatch */',
    '  constructor(dispatch) {',
    `    if (typeof dispatch !== 'function') throw new TypeError('${type} needs a dispatch function');`,
    '    this.#dispatch = dispatch;',
    '  }',
    '',
    '  /** Send one request and resolve to the response bytes. */',
    '  async invoke(request) {',
    '    return this.#dispatch(request);',
    '  }',
    '}',
  );
  const ts = lines(
    HEADER(from),
    '/** The model this client was generated from. It equals `inputs.model` in prismpm.lock. */',
    'export declare const MODEL: {',
    `  readonly name: ${quote(application.name)};`,
    '  readonly blake3: string;',
    '  readonly sha256: string;',
    '};',
    '',
    '/** Sends request bytes to the guest and returns its response bytes. */',
    'export type Dispatch = (request: Uint8Array) => Uint8Array | Promise<Uint8Array>;',
    '',
    doc('', description.slice(0, -1)),
    `export declare class ${type} {`,
    '  constructor(dispatch: Dispatch);',
    '  /** Send one request and resolve to the response bytes. */',
    '  invoke(request: Uint8Array): Promise<Uint8Array>;',
    '}',
  );
  return [
    [`${application.file}.js`, js],
    [`${application.file}.d.ts`, ts],
  ];
}

/** The files of the JavaScript bindings: the world, then the application's client. */
export function write(model) {
  const client = model.application.interface.kind === 'operations' ? operationsFiles(model.application) : bytesFiles(model.application);
  return [...worldFiles(model.world), ...client];
}
