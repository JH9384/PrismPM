/**
 * Builds browser.js, the single-file ES module for pages with no bundler and
 * no import map. No bundler is involved: each module under src/ becomes a
 * function scope that returns its exports, and its relative imports become
 * reads from the modules before it. Nothing else is rewritten.
 *
 * The build refuses any import that is not a relative path inside src/, so a
 * `node:` module or a package can never reach the browser file.
 *
 * `node scripts/build-browser.mjs` writes browser.js. `--check` fails when the
 * committed browser.js differs from a fresh build.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, relative, resolve } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = resolve(root, 'src');
const entry = resolve(src, 'index.mjs');
const check = process.argv.includes('--check');

const IMPORT = /^import\s+(?:\*\s+as\s+(\w+)|\{([^}]*)\})\s+from\s+'([^']+)';\s*$/;
const EXPORT_DECLARATION = /^export\s+(async\s+function\*?|function\*?|class|const|let)\s+(\w+)/;

/** Parse one module: its imports, its export names, and its body with `export` keywords removed. */
function load(file) {
  const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const imports = [];
  const exports = [];
  const lines = [];
  for (const line of text.split('\n')) {
    if (/^\s*import[\s({*]/.test(line) || /\bimport\s*\(/.test(line) || /\brequire\s*\(/.test(line)) {
      const match = IMPORT.exec(line);
      if (!match) throw new Error(`${relative(root, file)}: unsupported import form: ${line.trim()}`);
      const [, namespace, names, specifier] = match;
      if (!specifier.startsWith('./') && !specifier.startsWith('../')) {
        throw new Error(`${relative(root, file)}: imports ${specifier}; the browser build accepts relative imports only`);
      }
      const target = resolve(dirname(file), specifier);
      if (!target.startsWith(src)) throw new Error(`${relative(root, file)}: imports ${specifier}, outside src/`);
      imports.push({ target, namespace, names: names?.split(',').map((n) => n.trim()).filter(Boolean) });
      continue;
    }
    if (/^export\s*\{/.test(line) || /^export\s+\*/.test(line) || /^export\s+default\b/.test(line)) {
      throw new Error(`${relative(root, file)}: unsupported export form: ${line.trim()}`);
    }
    const declaration = EXPORT_DECLARATION.exec(line);
    if (declaration) {
      exports.push(declaration[2]);
      lines.push(line.replace(/^export\s+/, ''));
      continue;
    }
    if (/^export\b/.test(line)) throw new Error(`${relative(root, file)}: unsupported export form: ${line.trim()}`);
    lines.push(line);
  }
  return { file, imports, exports, body: lines.join('\n').trim() };
}

/** Modules in dependency order, the entry last. */
function collect() {
  const ordered = [];
  const seen = new Map();
  const visit = (file, path) => {
    if (seen.get(file) === 'done') return;
    if (seen.get(file) === 'visiting') throw new Error(`import cycle: ${[...path, file].map((f) => relative(root, f)).join(' -> ')}`);
    seen.set(file, 'visiting');
    const module = load(file);
    for (const dependency of module.imports) visit(dependency.target, [...path, file]);
    seen.set(file, 'done');
    ordered.push(module);
  };
  visit(entry, []);
  return ordered;
}

function variable(file) {
  return `__${relative(src, file).replace(/\.mjs$/, '').replace(/[^A-Za-z0-9]/g, '_')}`;
}

export function build() {
  const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
  const modules = collect();
  const parts = [
    `// ${pkg.name} ${pkg.version}, single-file browser build. GENERATED by scripts/build-browser.mjs from src/; do not edit.`,
    '// No imports, no Node built-ins, no network. Source and license: https://github.com/UOR-Foundation/PrismPM/tree/main/sdk/npm/verify',
    '',
  ];
  for (const module of modules) {
    const bindings = module.imports.map(({ target, namespace, names }) =>
      namespace ? `  const ${namespace} = ${variable(target)};` : `  const { ${names.join(', ')} } = ${variable(target)};`,
    );
    const indented = module.body
      .split('\n')
      .map((line) => (line ? `  ${line}` : line))
      .join('\n');
    parts.push(
      `// ${relative(root, module.file).replace(/\\/g, '/')}`,
      `const ${variable(module.file)} = (() => {`,
      ...bindings,
      indented,
      `  return Object.freeze({ ${module.exports.join(', ')} });`,
      '})();',
      '',
    );
  }
  const main = modules[modules.length - 1];
  parts.push(`export const { ${main.exports.join(', ')} } = ${variable(main.file)};`, '');
  return parts.join('\n');
}

const output = build();
const target = resolve(root, 'browser.js');
if (check) {
  let current = null;
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {}
  if (current !== output) {
    console.error('browser.js is stale; run node scripts/build-browser.mjs');
    process.exit(1);
  }
  console.log('browser.js is current');
} else {
  writeFileSync(target, output);
  console.log(`wrote browser.js, ${output.length} bytes`);
}
