/**
 * Copies the single-file build of @prism-code/verify into src/vendor/verify.mjs,
 * byte for byte below a header that names the origin.
 *
 * Why copy instead of depend: prism-code has no dependencies, and
 * @prism-code/verify is not published to npm yet. The copy is one file with no
 * imports, the same build a browser loads, so `holo.verify()` and
 * `@prism-code/verify` cannot disagree.
 *
 * `node scripts/vendor-verify.mjs` writes the file. `--check` fails when it
 * differs from what sdk/npm/verify/browser.js would produce today.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const origin = here('../../verify/browser.js');
const target = here('../src/vendor/verify.mjs');

const header =
  '// GENERATED by scripts/vendor-verify.mjs from sdk/npm/verify/browser.js. Do not edit; run `node scripts/vendor-verify.mjs`.\n\n';
const expected = header + readFileSync(origin, 'utf8').replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  let actual = null;
  try {
    actual = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // reported below
  }
  if (actual !== expected) {
    console.error('src/vendor/verify.mjs is not what sdk/npm/verify/browser.js produces today. Run: node scripts/vendor-verify.mjs');
    process.exit(1);
  }
  console.log('vendored verify is current');
} else {
  writeFileSync(target, expected);
  console.log('wrote src/vendor/verify.mjs');
}
